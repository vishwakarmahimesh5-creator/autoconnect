// Translation Helper
export const translate = (language, key, variables = {}) => {
  const selectedLanguage = translations[language] || translations.en;

  const value = key
    .split(".")
    .reduce((current, part) => current?.[part], selectedLanguage);

  let result =
    typeof value === "string"
      ? value
      : key.split(".").reduce((current, part) => current?.[part], translations.en) || key;

  Object.entries(variables).forEach(([name, replacement]) => {
    result = result.replaceAll(`{${name}}`, String(replacement));
  });

  return result;
};